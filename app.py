    copy_after = {"id": None}  # pending status-revert timer, if any
    last_copied = {"value": None}  # most recently copied example command

    try:
        from tkinter import font as tkfont
        list_font = tkfont.Font(font=results.cget("font"))
    except Exception:
        list_font = None

    def list_inner_width():
        """Current visible pixel width of the results listbox."""
        try:
            return max(0, results.winfo_width() - 6)
        except Exception:
            return 0

    def fit_line(text):
        """Truncate a list line with "…" to the visible list width."""
        if list_font is None:
            return text
        avail = list_inner_width()
        if avail <= 0:
            return text
        try:
            if list_font.measure(text) <= avail:
                return text
        except Exception:
            return text
        ellipsis = "…"
        low, high = 0, len(text)
        while low < high:
            mid = (low + high + 1) // 2
            try:
                width = list_font.measure(text[:mid] + ellipsis)
            except Exception:
                break
            if width <= avail:
                low = mid
            else:
                high = mid - 1
        if low <= 1:
            return ellipsis
        return text[:low] + ellipsis

    def display_line(section, entry):
        """Full list_line() text, fitted to the visible list width
        with an ellipsis."""
        return fit_line(list_line(section, entry))

