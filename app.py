def _token_search(entries, haystacks, query):
    """Shared AND-with-OR-fallback token matching over prebuilt haystacks.

    Empty or whitespace-only query returns all entries in order. The
    query is split into whitespace tokens; first pass returns entries
    matching EVERY token (AND), falling back to entries matching ANY
    token (OR) so one off word never empties the list.
    """
    text = (query or "").strip().casefold()
    if not text:
        return list(entries)
    tokens = text.split()
    results = [entry for entry, hay in zip(entries, haystacks)
               if all(token in hay for token in tokens)]
    if not results:
        results = [entry for entry, hay in zip(entries, haystacks)
                   if any(token in hay for token in tokens)]
    return results


def _command_haystack(cmd):
    """Single casefolded text of every searchable command field."""
    parts = [
        cmd.get("name", ""),
        cmd.get("description", ""),
        cmd.get("details", ""),
        cmd.get("warning", ""),
        cmd.get("keywords", ""),
        cmd.get("category", ""),
    ]
    for example_cmd, note in cmd.get("examples", []):
        parts.append(example_cmd)
        parts.append(note)
    return " ".join(parts).casefold()


def _basic_haystack(entry):
    """Single casefolded text of every searchable basics field."""
    parts = [
        entry.get("term", ""),
        entry.get("title", ""),
        entry.get("details", ""),
        entry.get("keywords", ""),
    ]
    for example_cmd, note in entry.get("examples", []):
        parts.append(example_cmd)
        parts.append(note)
    return " ".join(parts).casefold()


def _error_haystack(entry):
    """Single casefolded text of every searchable error field."""
    parts = [
        entry.get("error", ""),
        entry.get("title", ""),
        entry.get("cause", ""),
        entry.get("keywords", ""),
    ]
    parts.extend(entry.get("fix", []))
    parts.extend(entry.get("commands", []))
    return " ".join(parts).casefold()


def search_commands(query):
    """Token-based substring search over command fields.

    Empty or whitespace-only query returns all commands in order.
    The query is split into whitespace tokens; first pass returns
    entries matching EVERY token (AND), falling back to entries
    matching ANY token (OR) so one off word never empties the list.
    Entries are matched over name, category, description, details,
    warning, keywords and every example command with its note.
    """
    return _token_search(COMMANDS,
                         [_command_haystack(cmd) for cmd in COMMANDS],
                         query)


def search_basics(query):
    """Token-based substring search over basics entries.

    Same semantics as ``search_commands``: empty query returns all
    entries; AND over tokens with OR fallback. Matched over term,
    title, details, keywords and every example with its note.
    """
    return _token_search(BASICS,
                         [_basic_haystack(entry) for entry in BASICS],
                         query)


def search_errors(query):
    """Token-based substring search over error entries.

    Same semantics as ``search_commands``: empty query returns all
    entries; AND over tokens with OR fallback. Matched over error,
    title, cause, keywords and every fix step and command.
    """
    return _token_search(ERRORS,
                         [_error_haystack(entry) for entry in ERRORS],
                         query)


def categories():
    """Return sorted unique categories preserving first-seen order."""
    seen = []
    for cmd in COMMANDS:
        cat = cmd.get("category", "")
        if cat and cat not in seen:
            seen.append(cat)
    return seen


def detail_blocks(cmd):
    """Split a command entry into (text, tag) blocks for rendering.

    Tags: "title" (command name), "body" (plain explanation),
    "cmd" (example command line), "note" (example explanation),
    "warn" (danger warning). Headless-testable: no tkinter needed.
    """
    blocks = [(cmd.get("name", ""), "title")]
    blocks.append(("Категория: {}".format(cmd.get("category", "")), "body"))
    blocks.append(("", "body"))
    blocks.append((cmd.get("description", ""), "body"))
    details = cmd.get("details", "")
    if details:
        blocks.append(("", "body"))
        blocks.append((details, "body"))
    examples = cmd.get("examples", [])
    if examples:
        blocks.append(("", "body"))
        blocks.append(("Примеры:", "body"))
        for example_cmd, note in examples:
            blocks.append((example_cmd, "cmd"))
            if note:
                blocks.append((note, "note"))
    warning = cmd.get("warning", "")
    if warning:
        blocks.append(("", "body"))
        blocks.append(("Внимание: " + warning, "warn"))
    return blocks


def example_line_map(cmd):
    """Map 1-based details-pane line numbers to copyable commands.

    ``show_details`` renders one block per line starting at line 1,
    so block index + 1 is the Text line number. "cmd" blocks map to
    the command string (leading spaces stripped); every other line
    maps to None. Headless-testable: no tkinter needed.
    """
    return example_line_map_for(SECTION_COMMANDS, cmd)


def format_details(cmd):
    """Format a command entry for the details pane (plain text)."""
    return "\n".join(text for text, _tag in detail_blocks(cmd))


SECTION_COMMANDS = "commands"
SECTION_BASICS = "basics"
SECTION_ERRORS = "errors"
SECTIONS = (
    (SECTION_COMMANDS, "Команды"),
    (SECTION_BASICS, "Основы"),
    (SECTION_ERRORS, "Ошибки"),
)


def basic_blocks(entry):
    """Split a BASICS entry into (text, tag) blocks for rendering.

    Same tags as ``detail_blocks``: "title", "body", "cmd", "note".
    Headless-testable: no tkinter needed.
    """
    blocks = [(entry.get("title", "") or entry.get("term", ""), "title")]
    details = entry.get("details", "")
    if details:
        blocks.append(("", "body"))
        blocks.append((details, "body"))
    examples = entry.get("examples", [])
    if examples:
        blocks.append(("", "body"))
        blocks.append(("Примеры:", "body"))
        for example_cmd, note in examples:
            blocks.append((example_cmd, "cmd"))
            if note:
                blocks.append((note, "note"))
    return blocks


def error_blocks(entry):
    """Split an ERRORS entry into (text, tag) blocks for rendering.

    Same tags as ``detail_blocks``; fix steps are numbered "body"
    lines, fix commands are copyable "cmd" lines.
    Headless-testable: no tkinter needed.
    """
    blocks = [(entry.get("error", ""), "title")]
    cause = entry.get("cause", "")
    if cause:
        blocks.append(("", "body"))
        blocks.append(("Почему это происходит:", "body"))
        blocks.append((cause, "body"))
    fix = entry.get("fix", [])
    if fix:
        blocks.append(("", "body"))
        blocks.append(("Что делать:", "body"))
        for number, step in enumerate(fix, start=1):
            blocks.append(("  {}. {}".format(number, step), "body"))
    commands = entry.get("commands", [])
    if commands:
        blocks.append(("", "body"))
        blocks.append(("Команды:", "body"))
        for fix_cmd in commands:
            blocks.append((fix_cmd, "cmd"))
    return blocks


def detail_blocks_for(section, entry):
    """Dispatcher the UI calls: blocks for an entry of any section."""
    if section == SECTION_BASICS:
        return basic_blocks(entry)
    if section == SECTION_ERRORS:
        return error_blocks(entry)
    return detail_blocks(entry)


def example_line_map_for(section, entry):
    """Line number -> copyable command mapping for any section.

    Same contract as ``example_line_map``: 1-based Text line numbers,
    "cmd" lines map to the stripped command, others to None.
    Headless-testable: no tkinter needed.
    """
    mapping = {}
    for lineno, (text, tag) in enumerate(
            detail_blocks_for(section, entry), start=1):
        if tag == "cmd":
            mapping[lineno] = text.strip()
        else:
            mapping[lineno] = None
    return mapping


def list_line(section, entry):
    """One-line results-list text for an entry of any section.

    Command rows show the name and description with no marker
    glyphs, so every row aligns identically.
    """
    if section == SECTION_BASICS:
        return "{:<14}  {}".format(
            entry.get("term", ""), entry.get("title", ""))
    if section == SECTION_ERRORS:
        return entry.get("error", "")
    return "{:<22}  {}".format(
        entry.get("name", ""), entry.get("description", ""))


def section_search(section, query):
    """Search function for the active section (dispatcher)."""
    if section == SECTION_BASICS:
        return search_basics(query)
    if section == SECTION_ERRORS:
        return search_errors(query)
    return search_commands(query)


def section_total(section):
    """Total entry count of a section (for the status counter)."""
    if section == SECTION_BASICS:
        return len(BASICS)
    if section == SECTION_ERRORS:
        return len(ERRORS)
    return len(COMMANDS)


