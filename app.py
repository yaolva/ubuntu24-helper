    details.tag_config("cmd-visited", font=("Consolas", 10),
                       foreground="#551a8b",
                       lmargin1=20, lmargin2=20, spacing1=4)
    details.tag_config("note", font=("Segoe UI", 9, "italic"),
                       lmargin1=20, lmargin2=20)
    details.tag_config("warn", font=("Segoe UI", 10, "bold"),
                       foreground="red")

